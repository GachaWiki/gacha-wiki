// Generate the wiki card data files from tools/ws-carddb/sets/*.json.
// Usage: bun tools/ws-carddb/gen-data.mjs <setId> [setId...]
// Writes src/data/ws-cards/<setId>.js per set and regenerates the registry
// src/data/ws-cards/index.js (all previously generated sets stay registered).
import fs from 'node:fs';
import path from 'node:path';
import { SETS, HERE, REPO_ROOT } from './lib.mjs';

const setsDir = path.join(HERE, 'sets');
const outDir = path.join(REPO_ROOT, 'src', 'data', 'ws-cards');
fs.mkdirSync(outDir, { recursive: true });

const args = process.argv.slice(2);
const jsId = (setId) => setId.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const jsConst = (setId) => jsId(setId).replace(/^(.)/, (c) => c.toUpperCase()) + 'Set';

for (const setId of args) {
  const set = JSON.parse(fs.readFileSync(path.join(setsDir, `${setId}.json`), 'utf8'));
  const meta = SETS[setId];
  const cards = set.cards.map((c) => ({
    num: c.num,
    name: c.name,
    type: c.type,
    rarity: c.rarity,
    color: c.color,
    level: c.level,
    cost: c.cost,
    power: c.power,
    soul: c.soul,
    trigger: c.trigger,
    text: c.text,
    traits: c.traits?.length ? c.traits : undefined,
    // R2 URL once rehosted, otherwise the official cardlist image URL
    // (rehosting waves replace these over time)
    img: c.r2 || c.img || '',
    variant: c.variant,
  }));
  const body = `// Generated by tools/ws-carddb from the official Weiss Schwarz cardlist
// (${meta.name}, expansion ${meta.expansion}). Do not edit by hand.
export const ${jsConst(setId)} = {
  id: '${setId}',
  name: ${JSON.stringify(meta.name)},
  expansion: ${meta.expansion},
  lang: '${meta.lang || 'en'}',
  release: ${meta.release ? `'${meta.release}'` : 'null'},
  shopItem: ${meta.shopItem ? `'${meta.shopItem}'` : 'null'},
  box: ${set.boxImage ? JSON.stringify(set.boxImage) : 'null'},
  cards: ${JSON.stringify(cards, null, 1)},
};

export default ${jsConst(setId)};
`;
  fs.writeFileSync(path.join(outDir, `${setId}.js`), body);
  console.log(`[ok] src/data/ws-cards/${setId}.js (${cards.length} cards)`);
}

// Metadata registry (index.js): ids, counts and tile fields only, so pages
// that just list sets never pull every card into the build. Full card data
// is lazy-loaded per set via import.meta.glob in [set].astro.
const present = fs
  .readdirSync(outDir)
  .filter((f) => f.endsWith('.js') && f !== 'index.js' && f !== 'meta.js')
  .map((f) => f.replace('.js', ''));
const ordered = Object.keys(SETS).filter((id) => present.includes(id));

const metaRows = ordered.map((id) => {
  const meta = SETS[id];
  const json = JSON.parse(fs.readFileSync(path.join(setsDir, `${id}.json`), 'utf8'));
  const sample = json.cards.find((c) => c.img)?.img || '';
  return `  { id: '${id}', name: ${JSON.stringify(meta.name)}, lang: '${meta.lang || 'en'}', release: ${
    meta.release ? `'${meta.release}'` : 'null'
  }, shopItem: ${meta.shopItem ? `'${meta.shopItem}'` : 'null'}, box: ${
    json.boxImage ? JSON.stringify(json.boxImage) : 'null'
  }, sample: ${JSON.stringify(sample)}, count: ${json.cards.length} },`;
});
const registry = `// Generated by tools/ws-carddb/gen-data.mjs. Do not edit by hand.
// METADATA ONLY (no card arrays): importers that need full card data load the
// per-set file lazily (see [set].astro).
export const WS_CARD_SETS = [
${metaRows.join('\n')}
];

export function getCardSetCount() {
  return WS_CARD_SETS.reduce((n, s) => n + s.count, 0);
}
`;
fs.writeFileSync(path.join(outDir, 'index.js'), registry);
console.log(`[ok] src/data/ws-cards/index.js (${ordered.length} sets, metadata only)`);
