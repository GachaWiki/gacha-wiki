export function getEventStatus(event, now = new Date()) {
  if (!event.end) return 'live';
  const end = new Date(event.end + 'T00:59:00Z');
  const start = new Date(event.start + 'T15:00:00Z');
  if (now < start) return 'upcoming';
  return now <= end ? 'live' : 'ended';
}

export function getEventTypeLabel(type) {
  return { story: 'Story Event', login: 'Login Event', collab: 'Collaboration' }[type] || type;
}
